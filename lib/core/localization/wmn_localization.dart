import 'package:flutter/material.dart';

import '../settings/settings_repository.dart';

class WmnLocaleController extends ChangeNotifier {
  WmnLocaleController(this.settings)
      : _languageCode = settings.getString('language', fallback: 'ar');

  final SettingsRepository settings;
  String _languageCode;

  String get languageCode => _languageCode;
  Locale get locale => Locale(_languageCode);
  bool get isRtl => _languageCode == 'ar';

  void setLanguage(String languageCode) {
    if (languageCode == _languageCode) return;
    _languageCode = languageCode;
    settings.setString('language', languageCode);
    notifyListeners();
  }
}

