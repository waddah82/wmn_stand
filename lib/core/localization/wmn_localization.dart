class WmnL10nScope extends InheritedNotifier<WmnLocaleController> {
  const WmnL10nScope({
    super.key,
    required WmnLocaleController controller,
    required super.child,
  }) : super(notifier: controller);

  static WmnLocaleController controllerOf(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<WmnL10nScope>();
    if (scope == null) throw StateError('WMN localization scope is not available.');
    return scope.notifier!;
  }

  static WmnStrings of(BuildContext context) {
    final controller = controllerOf(context);
    return WmnStrings(controller.languageCode);
  }
}


extension WmnLocalizationContext on BuildContext {
  String wmnT(String key) => WmnL10nScope.of(this).t(key);
}
